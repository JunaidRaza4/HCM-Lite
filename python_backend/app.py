    @staticmethod
    def get_security_question(identifier: str) -> Dict[str, Any]:
        """Retrieves user security question by email or employee code."""
        conn = get_db_connection()
        try:
            clean_id = identifier.strip().lower()
            row = conn.execute("""
                SELECT u.email, u.name, u.security_question
                FROM users u
                LEFT JOIN employees e ON u.id = e.user_id
                WHERE LOWER(u.email) = ? OR LOWER(e.code) = ?
                LIMIT 1
            """, (clean_id, clean_id.upper())).fetchone()

            if not row:
                raise ValueError("No registered account matches the provided email or employee code.")

            question = row["security_question"] or "What was the brand or model of your first mobile phone?"
            return {
                "success": True,
                "question": question,
                "email": row["email"],
                "name": row["name"]
            }
        finally:
            conn.close()

    @staticmethod
    def verify_security_answer_and_reset(identifier: str, answer: str, new_password: str) -> Dict[str, Any]:
        """Validates security answer (case-insensitive) and resets password with strong rule check."""
        conn = get_db_connection()
        try:
            if not STRONG_PASSWORD_REGEX.match(new_password):
                raise ValueError("Use strong password: minimum 8 characters, including uppercase, lowercase, number, and special character.")

            clean_id = identifier.strip().lower()
            row = conn.execute("""
                SELECT u.id, u.email, u.name, u.security_answer
                FROM users u
                LEFT JOIN employees e ON u.id = e.user_id
                WHERE LOWER(u.email) = ? OR LOWER(e.code) = ?
                LIMIT 1
            """, (clean_id, clean_id.upper())).fetchone()

            if not row:
                raise ValueError("Account not found.")

            stored_answer = (row["security_answer"] or "").strip().lower()
            provided_answer = answer.strip().lower()

            if not stored_answer or stored_answer != provided_answer:
                raise ValueError("The provided security answer is incorrect. Verification failed.")

            new_hash = hash_password(new_password)
            now = datetime.utcnow().isoformat()

            with conn:
                conn.execute("""
                    UPDATE users
                    SET password_hash = ?, must_change_password = 0, updated_at = ?
                    WHERE id = ?
                """, (new_hash, now, row["id"]))

                conn.execute("""
                    INSERT INTO audit_logs (actor_id, actor_name, actor_role, action, entity, entity_id, details, created_at)
                    VALUES (?, ?, 'user', 'PASSWORD_RESET_VIA_SECURITY_QUESTION', 'user', ?, ?, ?)
                """, (row["id"], row["name"], row["id"], json.dumps({"email": row["email"]}), now))

            return {
                "success": True,
                "message": "Password reset successfully! You can now log in with your new strong password.",
                "email": row["email"]
            }
        finally:
            conn.close()

    @staticmethod
    def process_camera_check_in(employee_id: int, face_vector: List[float], gps: Dict[str, float]) -> Dict[str, Any]:
        """
        Processes facial biometric check-in:
        1. Validates GPS geofence against company office_lat/lng/radius using Haversine.
        2. Serializes ONLY the 128-float face vector embedding into JSON (zero image storage).
        3. Records attendance timestamp authoritatively from server clock.
        """
        conn = get_db_connection()
        try:
            today_str = date.today().isoformat()
            now_str = datetime.utcnow().isoformat()

            # Verify no duplicate check-in today
            existing = conn.execute("""
                SELECT id FROM attendance WHERE employee_id = ? AND date = ?
            """, (employee_id, today_str)).fetchone()
            if existing:
                raise ValueError("HTTP 409 Conflict: Attendance record already exists for today.")

            # Validate Geofence
            company = conn.execute("SELECT office_lat, office_lng, office_radius FROM companies LIMIT 1").fetchone()
            distance_meters = 0
            if company and company["office_lat"] is not None and company["office_lng"] is not None:
                if gps.get("accuracy", 0) > 100:
                    raise ValueError(f"GPS accuracy too low ({gps.get('accuracy')}m). Please move to an open area.")

                distance_meters = haversine_distance_meters(
                    float(company["office_lat"]), float(company["office_lng"]),
                    float(gps["lat"]), float(gps["lng"])
                )
                allowed_radius = company["office_radius"] or 150
                if distance_meters > allowed_radius:
                    raise ValueError(f"Geofence violation: You are {distance_meters}m away from the office (maximum allowed: {allowed_radius}m).")

            # Validate vector format
            if len(face_vector) != 128:
                raise ValueError(f"Biometric face descriptor must be a 128-element float vector (got {len(face_vector)} elements).")

            vector_json = json.dumps(face_vector)

            with conn:
                cur = conn.cursor()
                cur.execute("""
                    INSERT INTO attendance (employee_id, date, check_in_time, status, source,
                                           face_descriptor, lat, lng, accuracy, created_at, updated_at)
                    VALUES (?, ?, ?, 'present', 'camera', ?, ?, ?, ?, ?, ?)
                """, (employee_id, today_str, now_str, vector_json, gps["lat"], gps["lng"], gps.get("accuracy", 0), now_str, now_str))

            return {
                "success": True,
                "message": f"Biometric face check-in verified! Office distance: {distance_meters}m.",
                "distanceMeters": distance_meters
            }
        finally:
            conn.close()

    @staticmethod
    def process_camera_check_out(employee_id: int, face_vector: List[float], gps: Dict[str, float]) -> Dict[str, Any]:
        """
        Processes facial biometric check-out:
        1. Fetches morning check-in face vector descriptor.
        2. Calculates Euclidean Distance between check-out scan and check-in vector.
        3. If distance > 0.55, REJECTS check-out (identity fraud prevention).
        """
        conn = get_db_connection()
        try:
            today_str = date.today().isoformat()
            now_str = datetime.utcnow().isoformat()

            record = conn.execute("""
                SELECT * FROM attendance WHERE employee_id = ? AND date = ?
            """, (employee_id, today_str)).fetchone()

            if not record:
                raise ValueError("No check-in record found for today. Cannot check out.")

            if record["check_out_time"]:
                raise ValueError("Already checked out for today.")

            # Biometric Euclidean Distance Verification
            if not record["face_descriptor"]:
                raise ValueError("Morning check-in does not contain a biometric face vector for verification.")

            morning_vector = json.loads(record["face_descriptor"])
            distance = calculate_euclidean_distance(morning_vector, face_vector)

            if distance > FACE_MATCH_THRESHOLD:
                raise ValueError(
                    f"Biometric verification failed on check-out: Face does not match morning check-in "
                    f"(Euclidean distance: {distance:.3f}, allowed maximum: {FACE_MATCH_THRESHOLD})."
                )

            with conn:
                conn.execute("""
                    UPDATE attendance
                    SET check_out_time = ?, checkout_face_descriptor = ?, updated_at = ?
                    WHERE id = ?
                """, (now_str, json.dumps(face_vector), now_str, record["id"]))

            return {
                "success": True,
                "message": f"Biometric check-out verified! Face vector match score: {1.0 - distance:.2%} (distance {distance:.3f}).",
                "distanceScore": round(distance, 4)
            }
        finally:
            conn.close()


