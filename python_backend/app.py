def calculate_euclidean_distance(v1: List[float], v2: List[float]) -> float:
    """
    Computes Euclidean distance between two 128-float face embeddings.
    Formula: sqrt( sum( (v1[i] - v2[i])^2 ) )
    Threshold: <= 0.55 signifies the same human identity.
    """
    if len(v1) != len(v2) or len(v1) == 0:
        raise ValueError(f"Vector dimensions must match non-empty 128-float array (got {len(v1)} and {len(v2)})")
    
    sum_sq = sum((a - b) ** 2 for a, b in zip(v1, v2))
    return math.sqrt(sum_sq)

def haversine_distance_meters(lat1: float, lng1: float, lat2: float, lng2: float) -> int:
    """
    Computes great-circle distance between two GPS coordinates using Haversine formula.
    Returns integer meters rounded.
    """
    R = 6371000.0  # Earth's mean radius in meters
    phi1 = math.radians(lat1)
    phi2 = math.radians(lat2)
    delta_phi = math.radians(lat2 - lat1)
    delta_lambda = math.radians(lng2 - lng1)

    a = (math.sin(delta_phi / 2.0) ** 2 +
         math.cos(phi1) * math.cos(phi2) * (math.sin(delta_lambda / 2.0) ** 2))
    c = 2.0 * math.atan2(math.sqrt(a), math.sqrt(1.0 - a))
    return int(round(R * c))

def calculate_fbr_monthly_tax(annual_taxable_salary: float) -> float:
    """
    Calculates monthly withholding tax based on Pakistani FBR progressive slabs:
    - 0 to 600,000: 0%
    - 600,001 to 1,200,000: 5% of amount exceeding 600k
    - 1,200,001 to 2,200,000: 30,000 + 15% exceeding 1.2M
    - 2,200,001 to 3,200,000: 180,000 + 25% exceeding 2.2M
    - 3,200,001 to 4,100,000: 430,000 + 30% exceeding 3.2M
    - Above 4,100,000: 700,000 + 35% exceeding 4.1M
    """
    if annual_taxable_salary <= 600000:
        annual_tax = 0.0
    elif annual_taxable_salary <= 1200000:
        annual_tax = (annual_taxable_salary - 600000) * 0.05
    elif annual_taxable_salary <= 2200000:
        annual_tax = 30000 + (annual_taxable_salary - 1200000) * 0.15
    elif annual_taxable_salary <= 3200000:
        annual_tax = 180000 + (annual_taxable_salary - 2200000) * 0.25
    elif annual_taxable_salary <= 4100000:
        annual_tax = 430000 + (annual_taxable_salary - 3200000) * 0.30
    else:
        annual_tax = 700000 + (annual_taxable_salary - 4100000) * 0.35

    return round(annual_tax / 12.0, 2)

