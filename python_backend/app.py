class HCMLiteController:
    """Encapsulates all REST handlers and database workflows for HCM Lite."""

    @staticmethod
    def get_setup_status() -> Dict[str, Any]:
        """Checks whether the database has been initialized with a company and root admin."""
        conn = get_db_connection()
        try:
            company = conn.execute("SELECT id FROM companies LIMIT 1").fetchone()
            admin = conn.execute("SELECT id FROM users WHERE role = 'admin' LIMIT 1").fetchone()
            needs_setup = (company is None or admin is None)
            return {"needsSetup": needs_setup, "initialized": not needs_setup}
        finally:
            conn.close()

    @staticmethod
    def initialize_first_run_setup(payload: Dict[str, Any]) -> Dict[str, Any]:
        """
        Provisions company and admin with office GPS, security question, and zero dummy clutter.
        Enforces strong password policy.
        """
        conn = get_db_connection()
        try:
            admin_email = (payload.get("adminEmail") or "").strip().lower()
            existing = conn.execute("SELECT id FROM users WHERE LOWER(email) = ?", (admin_email,)).fetchone()
            if existing:
                raise ValueError(f"An account with email '{admin_email}' already exists. Please log in.")

            company_name = (payload.get("companyName") or "").strip()
            admin_name = (payload.get("adminName") or "").strip()
            admin_password = payload.get("adminPassword") or ""
            security_question = (payload.get("securityQuestion") or "What was the brand or model of your first mobile phone?").strip()
            security_answer = (payload.get("securityAnswer") or "").strip().lower()

            if not company_name or not admin_name or not admin_email:
                raise ValueError("companyName, adminName, and adminEmail are mandatory.")

            if not STRONG_PASSWORD_REGEX.match(admin_password):
                raise ValueError("Use strong password: minimum 8 characters, including uppercase, lowercase, number, and special character.")

            office_lat = payload.get("officeLat")
            office_lng = payload.get("officeLng")
            office_radius = int(payload.get("officeRadius", 150))
            office_start = payload.get("officeStart", "09:00")
            grace_period = int(payload.get("gracePeriodMins", 15))
            weekend_days = payload.get("weekendDays", "Saturday,Sunday")

            now = datetime.utcnow().isoformat()
            hashed_pwd = hash_password(admin_password)

            with conn:
                # 1. Insert Company
                cur = conn.cursor()
                cur.execute("""
                    INSERT INTO companies (name, office_start, grace_period_mins, weekend_days,
                                           office_lat, office_lng, office_radius, created_at, updated_at)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, (company_name, office_start, grace_period, weekend_days,
                      office_lat, office_lng, office_radius, now, now))
                company_id = cur.lastrowid

                # 2. Insert Root Admin linked to company_id
                cur.execute("""
                    INSERT INTO users (email, password_hash, name, role, must_change_password,
                                       security_question, security_answer, company_id, status, created_at, updated_at)
                    VALUES (?, ?, ?, 'admin', 0, ?, ?, ?, 'active', ?, ?)
                """, (admin_email, hashed_pwd, admin_name, security_question, security_answer, company_id, now, now))
                admin_id = cur.lastrowid

                # 3. Log Audit
                cur.execute("""
                    INSERT INTO audit_logs (actor_id, actor_name, actor_role, action, entity, entity_id, details, created_at)
                    VALUES (?, ?, 'admin', 'FIRST_RUN_SETUP_INITIALIZED', 'company', ?, ?, ?)
                """, (admin_id, admin_name, company_id, json.dumps({"company": company_name, "gps": [office_lat, office_lng]}), now))

            return {
                "success": True,
                "message": f"Company '{company_name}' successfully initialized for {admin_email}!",
                "adminEmail": admin_email,
                "companyId": company_id,
                "adminId": admin_id
            }
        finally:
            conn.close()

